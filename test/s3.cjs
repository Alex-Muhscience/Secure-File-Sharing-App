const { test } = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { Readable } = require('node:stream');
const { EventEmitter } = require('node:events');
const { promisify } = require('node:util');
const { execFile } = require('node:child_process');
const { MongoClient } = require('mongodb');
const { ListMultipartUploadsCommand } = require('@aws-sdk/client-s3');
const { loadConfig } = require('../src/config');
const { Storage } = require('../src/storage');
const { migrateStorage } = require('../src/migration');
const execute = promisify(execFile);
test('private S3 encryption, multipart cleanup, migration and cross-backend recovery', { skip: process.env.TEST_S3 !== 'true' }, async t => {
  const marker = crypto.randomBytes(6).toString('hex'), directory = await fs.mkdtemp(path.join(os.tmpdir(), 's3-'));
  const uri = process.env.TEST_MONGO_URI || 'mongodb://mongo:27017', client = new MongoClient(uri);
  const name = `s3_${marker}`, restoredName = `restore_s3_${marker}`, remoteRestoreName = `restore_remote_${marker}`;
  const db = client.db(name), restoreDirectory = path.join(directory, 'restore');
  const sourceUri = new URL(uri); sourceUri.pathname = `/${name}`;
  const env = { ...process.env, ENCRYPTION_KEY: '12'.repeat(32), OTP_SECRET: '34'.repeat(32), BACKUP_KEY: '56'.repeat(32),
    MONGO_URI: sourceUri.toString(), SMTP_HOST: 'mail', STORAGE_DIR: path.join(directory, 'source'), STORAGE_DRIVER: 's3', S3_PREFIX: `test-${marker}/` };
  const config = loadConfig(env), storage = new Storage(config);
  const restored = new Storage({ ...config, storage: restoreDirectory, s3: { ...config.s3, prefix: `restored-${marker}/` } });
  t.after(async () => {
    for (const instance of [storage, restored]) { for await (const object of instance.list(true)) await instance.remove(object.id); instance.close(); }
    for (const database of [name, restoredName, remoteRestoreName]) await client.db(database).dropDatabase();
    await client.close(); await fs.rm(directory, { recursive: true, force: true });
  });
  await client.connect(); await storage.init(); await restored.init();
  const upload = (instance, stream) => new Promise((resolve, reject) => instance._handleFile(new EventEmitter(), { stream }, (error, file) => error ? reject(error) : resolve(file)));
  const bytes = crypto.randomBytes(6 * 1024 * 1024), file = await upload(storage, Readable.from(bytes));
  assert.equal(file.storageBackend, 's3'); assert.equal(file.size, bytes.length);
  assert.deepEqual(await storage.decrypt(file), bytes);
  assert.notDeepEqual(await storage.readCiphertext(file), bytes);
  assert.deepEqual(await fs.readdir(config.storage), []);
  await assert.rejects(storage.decrypt({ ...file, tag: '00'.repeat(16) }));
  const other = new Storage({ ...config, storage: path.join(directory, 'other-process') }); await other.init();
  assert.deepEqual(await other.decrypt(file), bytes); other.close();
  const badCredentials = new Storage({ ...config, s3: { ...config.s3, secretAccessKey: '00'.repeat(32) } });
  await assert.rejects(badCredentials.ready()); badCredentials.close();
  await assert.rejects(upload(storage, Readable.from((async function* () {
    yield Buffer.alloc(5 * 1024 * 1024);
    await new Promise(resolve => setTimeout(resolve, 250));
    throw new Error('Interrupted upload');
  })())));
  await storage.cleanupMultipart(new Date(Date.now() + 1000));
  const uploads = await storage.stores.s3.client.send(new ListMultipartUploadsCommand({ Bucket: config.s3.bucket, Prefix: config.s3.prefix }));
  assert.equal((uploads.Uploads || []).length, 0);
  const local = new Storage({ ...config, storageDriver: 'filesystem' }); await local.init();
  const legacyBytes = Buffer.from('Existing encrypted pilot object');
  const legacy = await upload(local, Readable.from(legacyBytes)); delete legacy.storageBackend;
  const id = crypto.randomUUID(); await db.collection('transfers').insertOne({ _id: id, ...legacy, status: 'active', createdAt: new Date() });
  assert.equal(await migrateStorage({ db, storage, target: 's3' }), 1);
  const migrated = await db.collection('transfers').findOne({ _id: id });
  assert.deepEqual(migrated.retainedBackends, ['filesystem']); assert.equal(migrated.storageBackend, 's3');
  await storage.checkReferences(db);
  assert.deepEqual([...storage.requiredBackends].sort(), ['filesystem', 's3']);
  const unconfigured = new Storage({ ...config, storageDriver: 'filesystem', s3: null });
  await assert.rejects(unconfigured.checkReferences(db), /not configured/); unconfigured.close();
  assert.deepEqual(await storage.decrypt(migrated), legacyBytes);
  assert.deepEqual(await local.readCiphertext(legacy), await storage.readCiphertext(migrated));
  assert.equal(await migrateStorage({ db, storage, target: 's3' }), 0);
  const conflict = await upload(local, Readable.from(Buffer.from('Keep authenticated original'))); delete conflict.storageBackend;
  const conflictId = crypto.randomUUID(); await db.collection('transfers').insertOne({ _id: conflictId, ...conflict, status: 'active', createdAt: new Date() });
  await storage.importCiphertext(conflict.objectId, Buffer.from('Conflicting destination'));
  await assert.rejects(migrateStorage({ db, storage, target: 's3' }), /conflicts/);
  assert.equal((await db.collection('transfers').findOne({ _id: conflictId })).storageBackend, undefined);
  await storage.remove(conflict.objectId); assert.equal(await migrateStorage({ db, storage, target: 's3' }), 1);
  const archive = path.join(directory, 'backup.enc'), script = path.join(__dirname, '../scripts/backup.cjs');
  await execute(process.execPath, [script, 'create', archive], { env });
  await execute(process.execPath, [script, 'restore', archive, restoredName], { env: { ...env, STORAGE_DRIVER: 'filesystem', S3_ENDPOINT: '', STORAGE_DIR: restoreDirectory } });
  const recovered = await client.db(restoredName).collection('transfers').findOne({ _id: id });
  assert.equal(recovered.storageBackend, 'filesystem'); assert.equal(recovered.retainedBackends, undefined);
  const recoveredFS = new Storage({ ...config, storageDriver: 'filesystem', s3: null, storage: restoreDirectory });
  assert.deepEqual(await recoveredFS.decrypt(recovered), legacyBytes);
  await execute(process.execPath, [script, 'restore', archive, remoteRestoreName], { env: { ...env, S3_PREFIX: restored.config.s3.prefix, STORAGE_DIR: path.join(directory, 'remote-restore') } });
  const recoveredRemote = await client.db(remoteRestoreName).collection('transfers').findOne({ _id: id });
  assert.equal(recoveredRemote.storageBackend, 's3'); assert.deepEqual(await restored.decrypt(recoveredRemote), legacyBytes);
  assert.equal(await migrateStorage({ db, storage, target: 'filesystem' }), 2);
  const rolledBack = await db.collection('transfers').findOne({ _id: id }); assert.equal(rolledBack.storageBackend, 'filesystem');
  assert.deepEqual(await local.decrypt(rolledBack), legacyBytes);
  await storage.removeRecord(rolledBack);
  await assert.rejects(local.readCiphertext(rolledBack));
  await assert.rejects(storage.store('s3').read(rolledBack.objectId, config.maxSize));
  local.close();
});
