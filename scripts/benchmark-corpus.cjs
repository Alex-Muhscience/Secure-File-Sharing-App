const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
function random(size, seed) {
  const output = Buffer.alloc(size);
  for (let index = 0; index < size; index += 32) crypto.createHash('sha256').update(`${seed}:${index}`).digest().copy(output, index, 0, Math.min(32, size - index));
  return output;
}
