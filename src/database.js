async function initialize(db) {
  await Promise.all([
    db.collection('challenges').createIndex({ id: 1 }, { unique: true }),
    db.collection('challenges').createIndex({ expiresAt: 1 }, { expireAfterSeconds: 0 }),
    db.collection('sessions').createIndex({ expiresAt: 1 }, { expireAfterSeconds: 0 }),
    db.collection('downloadTickets').createIndex({ expiresAt: 1 }, { expireAfterSeconds: 0 }),
    db.collection('downloadGrants').createIndex({ expiresAt: 1 }, { expireAfterSeconds: 0 }),
    db.collection('downloadGrants').createIndex({ sessionHash: 1 }),
    db.collection('limits').createIndex({ expiresAt: 1 }, { expireAfterSeconds: 0 }),
    db.collection('transfers').createIndex({ owner: 1, createdAt: -1 }),
    db.collection('transfers').createIndex({ recipient: 1, createdAt: -1 }),
    db.collection('transfers').createIndex({ expiresAt: 1, status: 1 }),
    db.collection('transfers').createIndex({ orgId: 1, status: 1 }),
    db.collection('transfers').createIndex({ objectId: 1 }),
    db.collection('organizations').createIndex({ 'members.email': 1 }),
    db.collection('audit').createIndex({ orgId: 1, _id: 1 }),
    db.collection('usage').createIndex({ orgId: 1, at: -1 }),
    db.collection('invoices').createIndex({ orgId: 1, at: -1 }),
    db.collection('orders').createIndex({ orgId: 1 }, { unique: true, partialFilterExpression: { open: true } }),
    db.collection('orders').createIndex({ provider: 1, externalId: 1 }),
    db.collection('orders').createIndex({ provider: 1, externalId: 1 }, { name: 'provider_external_unique', unique: true, partialFilterExpression: { externalId: { $type: 'string' } } }),
    db.collection('orders').createIndex({ status: 1, nextAttempt: 1 }),
    db.collection('paymentEvents').createIndex({ processed: 1, nextAttempt: 1 }),
    db.collection('uploads').createIndex({ owner: 1, orgId: 1, fingerprint: 1 }, { unique: true, partialFilterExpression: { status: 'uploading' } }),
    db.collection('uploads').createIndex({ status: 1, expiresAt: 1 }),
    db.collection('chunks').createIndex({ uploadId: 1, index: 1 }, { unique: true }),
    db.collection('chunks').createIndex({ objectId: 1 }, { unique: true }),
    db.collection('chunks').createIndex({ uploadId: 1, offset: 1 }),
    db.collection('workers').createIndex({ heartbeat: 1 }, { expireAfterSeconds: 86400 }),
  ]);
}
module.exports = { initialize };
